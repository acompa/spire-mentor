"""The Rust board import and the Python adapter build the same engine wire (GH #1426).

The live advisor rebuilds a fight with ``sts2_rs.combat_wire_from_bridge``
(``sts2-workbench``'s ``combat_import``, which the browser workbench runs
too). The Python two-stage translation it replaced on that path
(``realgame_adapter.to_headless_combat_play`` + ``sts2_hint.adapter.translate``)
still serves the PPO env, the replays and the workbench, so the two must
stay one translation. They drifted once already: by 2026-11-16 the Rust copy
was missing co-op seats, the game build, Dread, Blitz, the act and floor and
every History counter, and read the v0.107.1 power and v0.111.0 card
registries, so it dropped every v0.113.0-only power and card.

The boards are every one the adapter-facing Python tests build
(``tests/fixtures/board_import/boards.jsonl.gz``, regenerated by
``scripts/harvest_adapter_boards.py``) and, where the private corpus is
present, every fight board of a recorded live run.
"""

from __future__ import annotations

import gzip
import json
import re
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import pytest
import sts2_rs
from realgame_adapter import (
    UnsupportedGameVersionError,
    character_display_name,
    combat_wire,
    run_ascension,
    to_headless_combat_play,
)
from sts2_hint import adapter

TESTS = Path(__file__).resolve().parent
BOARDS = TESTS / "fixtures" / "board_import" / "boards.jsonl.gz"
LIVE_CORPUS = TESTS.parent.parent / "logs" / "2026-11-07-instinct-live" / "run1-requests.jsonl.gz"


def _test_boards() -> list[dict[str, Any]]:
    with gzip.open(BOARDS, "rt", encoding="utf-8") as f:
        return [json.loads(line) for line in f]


def _live_boards() -> Iterator[dict[str, Any]]:
    """Every fight board of the recorded run, as the advisor sees it."""
    with gzip.open(LIVE_CORPUS, "rt", encoding="utf-8") as f:
        for line in f:
            msg = json.loads(line)
            if msg.get("type") != "advice_request":
                continue
            if msg.get("advice_for") == "combat_action":
                yield {**msg, "type": "combat_action"}
            elif isinstance(msg.get("combat"), dict):
                yield msg["combat"]


def _diff(py: Any, rust: Any, path: str = "$") -> list[str]:
    """Where two wire dicts differ, by JSON path (type-strict: 1 is not True)."""
    if isinstance(py, dict) and isinstance(rust, dict):
        out: list[str] = []
        for key in sorted(set(py) | set(rust)):
            if key not in rust:
                out.append(f"{path}.{key}: only in Python")
            elif key not in py:
                out.append(f"{path}.{key}: only in Rust")
            else:
                out += _diff(py[key], rust[key], f"{path}.{key}")
        return out
    if isinstance(py, list) and isinstance(rust, list) and len(py) == len(rust):
        return [
            d
            for i, (a, b) in enumerate(zip(py, rust, strict=True))
            for d in _diff(a, b, f"{path}[{i}]")
        ]
    if py != rust or type(py) is not type(rust):
        return [f"{path}: Python {py!r:.80} != Rust {rust!r:.80}"]
    return []


def _compare(board: dict[str, Any]) -> list[str]:
    """Both translations of *board*; the differences, or both errors' agreement."""
    run_state = board.get("run_state") or {}
    character = character_display_name(run_state.get("character")) or "Ironclad"
    ascension = run_ascension(run_state, 0)
    kwargs = {"character": character, "ascension": ascension, "combat_id": 7, "seed": 11}
    try:
        py = adapter.translate(to_headless_combat_play(board), **kwargs)
    except (ValueError, KeyError, TypeError) as exc:
        py, py_err = None, exc
    else:
        py_err = None
    try:
        rust = combat_wire(board, **kwargs)
    except ValueError as exc:
        rust, rust_err = None, exc
    else:
        rust_err = None
    if py_err is not None or rust_err is not None:
        if (py_err is None) != (rust_err is None):
            return [f"only one side refused the board: Python {py_err!r}, Rust {rust_err!r}"]
        return []
    return _diff(py, rust)


def _summarize(failures: dict[str, list[str]]) -> str:
    """Each distinct difference (indices folded) once, with a board that shows it."""
    seen: dict[str, str] = {}
    for board, diffs in failures.items():
        for d in diffs:
            seen.setdefault(re.sub(r"\[\d+\]", "[]", d.split(":")[0]), f"{board}: {d}")
    return "\n".join(sorted(seen.values()))


def test_every_test_board_gets_the_same_wire_from_rust_and_python() -> None:
    boards = _test_boards()
    assert len(boards) >= 100, "re-run scripts/harvest_adapter_boards.py"
    failures = {f"board {i}": d for i, b in enumerate(boards) if (d := _compare(b))}
    assert not failures, f"{len(failures)}/{len(boards)} boards differ:\n{_summarize(failures)}"


def test_every_live_board_gets_the_same_wire_from_rust_and_python() -> None:
    n = 0
    failures: dict[str, list[str]] = {}
    for i, board in enumerate(_live_boards()):
        n += 1
        if d := _compare(board):
            failures[f"live board {i}"] = d
    assert n > 600, n
    assert not failures, f"{len(failures)}/{n} boards differ:\n{_summarize(failures)}"


def test_the_harvested_boards_cover_what_the_rust_copy_once_lacked() -> None:
    """The fixture still exercises each field the Rust copy had drifted on."""
    wires = []
    for board in _test_boards():
        run_state = board.get("run_state") or {}
        try:
            wires.append(
                combat_wire(
                    board,
                    character=character_display_name(run_state.get("character")) or "Ironclad",
                    ascension=run_ascension(run_state, 0),
                )
            )
        except ValueError:
            continue
    keys = {k for w in wires for k in w}
    player_keys = {k for w in wires for k in w["player"]}
    for key in ("allies", "coop_full", "game_version", "act_index", "is_boss", "total_floor"):
        assert key in keys, key
    assert {"dread", "blitz"} <= {w.get("game_mode") for w in wires}
    for key in ("hp_lost_this_turn", "unblocked_hits_this_combat", "card_block_gains_this_turn"):
        assert key in player_keys, key


def test_an_unsupported_build_is_refused_with_the_advisors_error() -> None:
    board = _test_boards()[0] | {"game_version": "v0.200.0"}
    with pytest.raises(UnsupportedGameVersionError):
        combat_wire(board, character="Ironclad", ascension=0)


def test_the_callers_combat_id_and_seed_reach_the_wire() -> None:
    board = next(b for b in _test_boards() if not _compare(b) and "allies" not in b)
    wire = combat_wire(board, character="Ironclad", ascension=0, combat_id=7, seed=11)
    assert wire["combat_id"] == 7
    assert wire["rng"]["seed"] == 11


def test_rust_raises_its_unsupported_state_error_on_an_unknown_monster() -> None:
    board = next(b for b in _test_boards() if b.get("enemies"))
    board = json.loads(json.dumps(board))
    board["enemies"][0]["name"] = "Not A Monster"
    board["enemies"][0]["id"] = "NOT_A_MONSTER"
    with pytest.raises(sts2_rs.UnsupportedStateError, match="unknown monster"):
        combat_wire(board, character="Ironclad", ascension=0)


def test_with_no_character_the_class_comes_from_the_cards() -> None:
    """Like ``translate``: a lane whose run state names no character."""
    board = next(
        b
        for b in _test_boards()
        if (b.get("run_state") or {}).get("character") == "DEFECT" and not _compare(b)
    )
    wire = combat_wire(board, character=None, ascension=0)
    assert wire["player"]["class"] == "defect"
    assert wire == adapter.translate(to_headless_combat_play(board), ascension=0)


def test_a_resolving_card_is_not_counted_as_played_yet() -> None:
    """The game counts a play when it starts (`CardPlaysStarted`), the engine
    when it finishes (`CardPlaysFinished`, which most C# mechanics read). At a
    mid-play choice the card still resolves in the play pile, so both twins
    drop it from the board's count (Spire Bench corpus: `PLAYED` one high)."""
    board = next(b for b in _test_boards() if (b.get("play_pile") or {}).get("cards"))
    types = [c["type"] for c in board["play_pile"]["cards"]]
    order = ["Attack", "Skill", "Power", "Curse", "Status"]
    played = [2 + types.count(t) for t in order]
    board = {**board, "player": {**board["player"], "cards_played_this_turn": played}}
    assert _compare(board) == []
    run_state = board.get("run_state") or {}
    kwargs = {
        "character": character_display_name(run_state.get("character")) or "Ironclad",
        "ascension": run_ascension(run_state, 0),
        "combat_id": 7,
        "seed": 11,
    }
    rust = combat_wire(board, **kwargs)
    assert rust["player"]["cards_played_this_turn"] == [2] * 5
